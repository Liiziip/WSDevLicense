#!/usr/bin/env python3
"""Emit src/midl_blob.c/h: the MIDL stub descriptor data copied verbatim from arm.exe."""
import os, struct, sys
from pedump import PE

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(BASE, "arm.exe")      # your own copy of the binary
d = open(SRC, "rb").read()
p = PE(d)

def blob(va, n):
    o = p.off(va - p.base)
    return d[o:o + n]

PROC_FMT_VA, PROC_FMT_LEN = 0x401890, 0x10A
TYPE_FMT_VA, TYPE_FMT_LEN = 0x40199A, 0x9E

def carray(name, data):
    lines = ["const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append("    " + " ".join("0x%02x," % b for b in chunk))
    lines.append("};")
    return "\n".join(lines)

out = []
out.append("/* Generated by tools/mkblobs.py from arm.exe - do not edit by hand. */")
out.append('#include "midl_blob.h"')
out.append("")
out.append("/* Procedure format string table, VA 0x401890 (offsets 0x02, 0x30, 0x5e are used). */")
out.append(carray("g_procFormat", blob(PROC_FMT_VA, PROC_FMT_LEN)))
out.append("")
out.append("/* Type format string, VA 0x40199A (pFormatTypes of the stub descriptor). */")
out.append(carray("g_typeFormat", blob(TYPE_FMT_VA, TYPE_FMT_LEN)))
out.append("")
# RPC_CLIENT_INTERFACE at 0x401A38: 0x44 bytes, rebuilt field by field
iface = blob(0x401A38, 0x44)
length = struct.unpack_from("<I", iface, 0)[0]
iid = iface[4:20]
iid_ver = struct.unpack_from("<HH", iface, 20)
xfer = iface[24:40]
xfer_ver = struct.unpack_from("<HH", iface, 40)
out.append("/* RPC_CLIENT_INTERFACE (VA 0x401A38), Length=0x%X. */" % length)
out.append("const RPC_CLIENT_INTERFACE g_clientInterface = {")
out.append("    /* Length                */ 0x%X," % length)
out.append("    /* InterfaceId           */ { { 0x%08X, 0x%04X, 0x%04X, { 0x%02x,0x%02x,0x%02x,0x%02x,0x%02x,0x%02x,0x%02x,0x%02x } }, { %d, %d } },"
           % (struct.unpack_from("<I", iid, 0)[0],
              struct.unpack_from("<H", iid, 4)[0],
              struct.unpack_from("<H", iid, 6)[0],
              iid[8], iid[9], iid[10], iid[11], iid[12], iid[13], iid[14], iid[15],
              iid_ver[0], iid_ver[1]))
out.append("    /* TransferSyntax        */ { { 0x%08X, 0x%04X, 0x%04X, { 0x%02x,0x%02x,0x%02x,0x%02x,0x%02x,0x%02x,0x%02x,0x%02x } }, { %d, %d } },"
           % (struct.unpack_from("<I", xfer, 0)[0],
              struct.unpack_from("<H", xfer, 4)[0],
              struct.unpack_from("<H", xfer, 6)[0],
              xfer[8], xfer[9], xfer[10], xfer[11], xfer[12], xfer[13], xfer[14], xfer[15],
              xfer_ver[0], xfer_ver[1]))
out.append("    /* DispatchTable         */ 0,")
out.append("    /* RpcProtseqEndpointCount*/ 0,")
out.append("    /* RpcProtseqEndpoint    */ 0,")
out.append("    /* Reserved              */ 0,")
out.append("    /* InterpreterInfo       */ 0,")
out.append("    /* Flags                 */ 0")
out.append("};")
out.append("")
# GUID at 0x401AD0 (kept for completeness; referenced by the original stub area)
g = blob(0x401AD0, 16)
out.append("/* GUID found at VA 0x401AD0 next to the stub descriptor. */")
out.append("const unsigned char g_auxGuid[16] = { %s };"
           % ", ".join("0x%02x" % b for b in g))
open(os.path.join(BASE, "src", "midl_blob.c"), "w", encoding="utf-8").write("\n".join(out) + "\n")

hdr = """/* Generated by tools/mkblobs.py - do not edit by hand. */
#ifndef MIDL_BLOB_H
#define MIDL_BLOB_H

#include <windows.h>
#include <rpc.h>

#ifdef __cplusplus
extern "C" {
#endif

extern const unsigned char g_procFormat[%d];
extern const unsigned char g_typeFormat[%d];
extern const RPC_CLIENT_INTERFACE g_clientInterface;
extern const unsigned char g_auxGuid[16];

#ifdef __cplusplus
}
#endif

#endif /* MIDL_BLOB_H */
""" % (PROC_FMT_LEN, TYPE_FMT_LEN)
open(r"D:\DSH\workspace\src\midl_blob.h", "w", encoding="utf-8").write(hdr)
print("wrote midl_blob.c/.h")
print("proc fmt: %d bytes, type fmt: %d bytes" % (PROC_FMT_LEN, TYPE_FMT_LEN))
